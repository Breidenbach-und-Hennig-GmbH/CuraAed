test('Ampel: beide Anmeldungen, Telefonat, Abmeldung und veraltete/unbekannte Signale',()=>{
 const now=1000000,s=(angemeldet,telefoniert,empfangen_am=now)=>({angemeldet,telefoniert,empfangen_am});
 assert.equal(svc.auswerten(true,'467',s(true,false),now).farbe,'gruen');
 assert.equal(svc.auswerten(true,'467',s(true,true),now).farbe,'gelb');
 assert.equal(svc.auswerten(true,'467',s(false,false),now).farbe,'rot');
 assert.equal(svc.auswerten(false,'467',s(true,true),now).farbe,'rot');
 assert.equal(svc.auswerten(false,'467',null,now).farbe,'rot');
 for(const snapshot of [null,{},s(true,false,now-90001),s(true,false,now+5001),s(false,true)])assert.equal(svc.auswerten(true,'467',snapshot,now).farbe,'grau');
 assert.equal(svc.auswerten(true,null,s(true,false),now).farbe,'grau');
});
test('CuraAed: offene Fenster statt langlebiger Cookies, mehrere Fenster/Sitzungen, verspätete Meldungen und Logout',async t=>{
 const db=await openDatabase(':memory:');t.after(()=>db.close());
 const u=await users.anlegen(db,{benutzername:'a',name:'A',passwort:'test12345'});
 const token=await auth.sitzungErstellen(db,u.id),other=await auth.sitzungErstellen(db,u.id),now=Date.now();
 const tab1='fenster-eins-12345',tab2='fenster-zwei-12345';
 assert.equal((await svc.onlineIds(db,now)).size,0);
 await svc.melden(db,token,{fenster_id:tab1,zustand:'offen'},now);
 await svc.melden(db,token,{fenster_id:tab2,zustand:'offen'},now);
 await svc.melden(db,token,{fenster_id:tab1,zustand:'geschlossen'},now+1);
 await svc.melden(db,token,{fenster_id:tab1,zustand:'offen'},now+2);
 assert.equal((await db.get('SELECT geschlossen FROM mitarbeiter_anwesenheit WHERE fenster_id=?',[tab1])).geschlossen,1);
 assert.equal((await svc.onlineIds(db,now+2)).has(u.id),true);
 assert.equal((await svc.onlineIds(db,now+120001)).has(u.id),false);
 await svc.melden(db,other,{fenster_id:tab1,zustand:'offen'},now+3);
 await auth.sitzungLoeschen(db,token);
 assert.equal((await svc.onlineIds(db,now+4)).has(u.id),true);
 await auth.sitzungLoeschen(db,other);
 assert.equal((await svc.onlineIds(db,now+5)).has(u.id),false);
 assert.equal((await db.get('SELECT COUNT(*) n FROM mitarbeiter_anwesenheit')).n,0);
 await assert.rejects(svc.melden(db,token,{fenster_id:tab1,zustand:'offen'}),e=>e.status===401);
});
test('STARFACE-Signale bleiben serverseitig; bei fehlender Anbindung oder Ausfall wird kein Grün erfunden',async t=>{
 const db=await openDatabase(':memory:');t.after(()=>db.close());
 const u=await users.anlegen(db,{benutzername:'a',name:'A',passwort:'test12345'}),now=Date.now();
 await require('../services/mitarbeiterprofile').speichern(db,u.id,{revision:0,starface_login_id:'467'});
 const token=await auth.sitzungErstellen(db,u.id);
 await svc.melden(db,token,{fenster_id:'fenster-eins-12345',zustand:'offen'},now);
 assert.equal((await svc.liste(db,undefined,now)).get(u.id).farbe,'grau');
 const fakeAdapter={statusFuerLogins:async ids=>{assert.deepEqual(ids,['467']);return new Map([['467',{angemeldet:true,telefoniert:true,empfangen_am:now}]]);}};
 assert.equal((await svc.liste(db,fakeAdapter,now)).get(u.id).farbe,'gelb');
 assert.equal((await svc.liste(db,{statusFuerLogins:async()=>{throw Error('offline');}},now)).get(u.id).farbe,'grau');
});
test('Anwesenheits-API bindet Fenster an die eigene Sitzung und prüft Herkunft sowie Rolle',async t=>{
 const db=await openDatabase(':memory:');t.after(()=>db.close());
 const a=await users.anlegen(db,{benutzername:'a',name:'A',passwort:'test12345'}),b=await users.anlegen(db,{benutzername:'b',name:'B',passwort:'test12345'}),reader=await users.anlegen(db,{benutzername:'r',name:'R',passwort:'test12345',rolle:'leser'});
 const token=await auth.sitzungErstellen(db,a.id),rToken=await auth.sitzungErstellen(db,reader.id);
 const app=require('../lib/appFactory').baueApp(db,{hausperfekt:{publicUrl:'https://curaaed.test'}});
 const server=await new Promise(r=>{const s=app.listen(0,'127.0.0.1',()=>r(s));});t.after(()=>new Promise(r=>server.close(r)));
 const base='http://127.0.0.1:'+server.address().port+'/api/mitarbeiterprofile';
 const post=(session,origin,body)=>fetch(base+'/praesenz',{method:'POST',headers:{cookie:'hv_session='+session,origin,'content-type':'application/json'},body:JSON.stringify(body)});
 const body={fenster_id:'fenster-test-12345',zustand:'offen',benutzer_id:b.id,starface:{angemeldet:true,telefoniert:false}};
 assert.equal((await post(token,'https://evil.test',body)).status,403);
 assert.equal((await post(rToken,'https://curaaed.test',body)).status,403);
 assert.equal((await post(token,'https://curaaed.test',{...body,fenster_id:'x'})).status,400);
 assert.equal((await post(token,'https://curaaed.test',body)).status,200);
 const data=await(await fetch(base,{headers:{cookie:'hv_session='+token}})).json();
 assert.equal(data.find(r=>r.id===a.id).status.farbe,'grau');
 assert.equal(data.find(r=>r.id===b.id).status.farbe,'rot');
});
