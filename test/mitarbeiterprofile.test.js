'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {openDatabase}=require('../db'),users=require('../services/benutzer'),svc=require('../services/mitarbeiterprofile');
test('Persönliche STARFACE-ID bleibt getrennt, Bilder werden normalisiert, Konflikte und fehlerhafte Bilder verworfen',async t=>{
 const db=await openDatabase(':memory:');t.after(()=>db.close());
 const a=await users.anlegen(db,{benutzername:'a',name:'A',passwort:'test12345'});
 const b=await users.anlegen(db,{benutzername:'b',name:'B',passwort:'test12345'});
 const {createCanvas}=require('@napi-rs/canvas'),canvas=createCanvas(32,48);canvas.getContext('2d').fillRect(0,0,32,48);
 const image=canvas.toDataURL('image/png');
 const p=await svc.speichern(db,a.id,{revision:0,starface_login_id:'00467',bild:image});
 assert.equal(p.starface_login_id,'00467');assert.equal(p.revision,1);assert.match(p.bild_url,/bild/);
 assert.equal((await svc.eigenes(db,b.id)).starface_login_id,null);
 assert.equal((await db.get('SELECT bild FROM mitarbeiterprofile WHERE benutzer_id=?',[a.id])).bild.readUInt32BE(16),256);
 assert.ok((await svc.liste(db)).every(r=>!('starface_login_id' in r)&&!('bild' in r)));
 const kept=await svc.speichern(db,a.id,{revision:1,starface_login_id:'467'});assert.equal(kept.hat_bild,1);
 await assert.rejects(svc.speichern(db,a.id,{revision:0,starface_login_id:'99'}),e=>e.status===409);
 for(const id of ['1e2','467x','-1',467,{},'1'.repeat(21)])await assert.rejects(svc.speichern(db,a.id,{revision:2,starface_login_id:id}));
 await assert.rejects(svc.speichern(db,a.id,{revision:2,starface_login_id:'467',bild:'data:image/png;base64,AAAA'}));
 assert.equal((await svc.eigenes(db,a.id)).revision,2);
 const cleared=await svc.speichern(db,a.id,{revision:2,starface_login_id:'',bild:null});assert.match(cleared.bild_url,/platzhalter/);assert.equal(cleared.starface_login_id,null);
});
test('Profil-API: Anmeldung, Rollen, Herkunft, eigene ID und keine fremden Login-IDs',async t=>{
 const db=await openDatabase(':memory:');t.after(()=>db.close());
 for(const [benutzername,rolle] of [['a','mitarbeiter'],['b','mitarbeiter'],['r','leser']])await users.anlegen(db,{benutzername,name:benutzername,passwort:'test12345',rolle});
 const app=require('../lib/appFactory').baueApp(db,{hausperfekt:{publicUrl:'https://curaaed.test'}});
 const server=await new Promise(r=>{const s=app.listen(0,'127.0.0.1',()=>r(s));});t.after(()=>new Promise(r=>server.close(r)));
 const base='http://127.0.0.1:'+server.address().port+'/api';
 const login=async name=>(await fetch(base+'/auth/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({benutzername:name,passwort:'test12345'})})).headers.get('set-cookie').split(';')[0];
 const a=await login('a'),b=await login('b'),reader=await login('r');
 const put=(cookie,origin,extra={})=>fetch(base+'/mitarbeiterprofile/ich',{method:'PUT',headers:{cookie,origin,'content-type':'application/json'},body:JSON.stringify({revision:0,starface_login_id:'467',...extra})});
 assert.equal((await fetch(base+'/mitarbeiterprofile')).status,401);
 assert.equal((await fetch(base+'/mitarbeiterprofile',{headers:{cookie:reader}})).status,403);
 assert.equal((await put(a,'https://evil.test')).status,403);
 assert.equal((await put(a,'https://curaaed.test',{benutzer_id:2,rolle:'admin'})).status,200);
 const other=await(await fetch(base+'/mitarbeiterprofile/ich',{headers:{cookie:b}})).json();assert.equal(other.starface_login_id,null);
 const team=await(await fetch(base+'/mitarbeiterprofile',{headers:{cookie:b}})).json();assert.equal(team.length,2);assert.ok(team.every(r=>!('starface_login_id' in r)));
 assert.equal((await db.get("SELECT rolle FROM benutzer WHERE benutzername='a'")).rolle,'mitarbeiter');
 const missing=await fetch(base+'/mitarbeiterprofile/2/bild',{headers:{cookie:b}});assert.equal(missing.status,200);assert.match(missing.headers.get('content-type'),/svg/);
});
